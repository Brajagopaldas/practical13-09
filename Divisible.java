class Divisible {
    public static void main(String[] args) {
        int number = 50;
        
        if (number % 5 == 0 && number % 10 == 0 ) {
            System.out.println("Number is divisible by both 5 and 10");
        } else {
            System.out.println("Number is Not divisible by both 5 and 10");
        }
        
    }
}
